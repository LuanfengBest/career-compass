import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createRequire} from 'node:module';
const dir=mkdtempSync(join(tmpdir(),'career-continuation-'));
process.env.CAREER_DB_PATH=join(dir,'test.sqlite');
process.env.TOKEN_ENCRYPTION_KEY=Buffer.alloc(32,7).toString('hex');
const require=createRequire(import.meta.url);
const s=require('../.test-build/server/task-store.js');
const a=require('../.test-build/server/task-actions.js');
let n=0; const id=()=>`continuation-${++n}`;
const claim=t=>a.agentTaskAction(t.owner,{action:'claim',taskId:t.id,usesLocalBrowser:false}).task;
const complete=t=>a.agentTaskAction(t.owner,{action:'report',taskId:t.id,claimToken:t.claimToken,eventId:id(),status:'completed',summary:'Actual fixture discovery',coverage:'Fixture source checked'});
const legacy='Claim expired. Check the external page before retrying; no automatic retry.';
test('expired discovery resumes same task, fences stale claim and releases once both finish',()=>{
 const r=a.agentTaskAction('muse',{action:'begin_discovery_round',roundKey:id(),title:'Recovery fixture',brief:'Fixture only',channel:'email',prepareApplications:true});
 const tasks=s.allTasks().filter(t=>t.batchId===r.batch.id);
 const dot=claim(tasks.find(t=>t.owner==='dot')); complete(dot);
 const muse=claim(tasks.find(t=>t.owner==='muse'));
 s.recordDiscovery('muse',r.batch.id,'contact','already-saved','Fixture evidence');
 s.saveTask({...muse,leaseUntil:new Date(0).toISOString()});
 const queued=s.taskSnapshot('muse').tasks.find(t=>t.id===muse.id);
 assert.equal(queued.status,'queued');assert.equal(queued.claimToken,undefined);
 assert.equal(s.allDiscoveries().filter(d=>d.batchId===r.batch.id).length,1);
 const renewed=claim(queued);assert.notEqual(renewed.claimToken,muse.claimToken);
 assert.throws(()=>complete(muse),/CLAIM_TOKEN_MISMATCH/);
 const done=complete(renewed);assert.equal(done.batch.status,'released');
 assert.equal(s.allBatches().filter(b=>b.id===r.batch.id).length,1);
});
test('legacy expiry blocks recover; explicit blocks, cancelled rounds and external actions do not retry',()=>{
 const safe=s.newTask('draft','muse','Legacy draft',{}, {status:'blocked',result:{summary:legacy}});s.saveTask(safe);
 const explicit=s.newTask('draft','muse','Explicit failure',{}, {status:'blocked',result:{summary:'Missing recipient identity'}});s.saveTask(explicit);
 const prep=s.newTask('application_prepare','muse','External form',{}, {status:'claimed',leaseUntil:new Date(0).toISOString(),claimToken:'old'});s.saveTask(prep);
 const send=s.newTask('linkedin_send','muse','External send',{}, {status:'claimed',leaseUntil:new Date(0).toISOString(),claimToken:'old'});s.saveTask(send);
 const batch={id:id(),title:'Cancelled',brief:'Fixture',createdAt:new Date().toISOString(),version:1,status:'cancelled',channel:'email',prepareApplications:true};s.saveBatch(batch);
 const cancelled=s.newTask('discover','muse','Cancelled discovery',{}, {batchId:batch.id,status:'blocked',result:{summary:legacy}});s.saveTask(cancelled);
 const snapshot=s.taskSnapshot();const state=t=>snapshot.tasks.find(x=>x.id===t.id).status;
 assert.equal(state(safe),'queued');assert.equal(state(explicit),'blocked');assert.equal(state(prep),'blocked');assert.equal(state(send),'uncertain');assert.equal(state(cancelled),'blocked');
});
test('review amendment is versioned, same-owner, idempotent, and cannot approve or overwrite submission',()=>{
 const t=s.newTask('application_prepare','muse','Prepared form',{}, {entityId:'fixture-job',status:'review',result:{summary:'Old report',answers:'Old answers',formState:'not_opened'}});s.saveTask(t);
 const input={action:'amend_preparation',taskId:t.id,version:t.version,eventId:id(),summary:'Actual partial form',answers:'Observed answers; missing work authorization response',formState:'partially_filled',evidenceUrl:'https://example.com/application'};
 assert.throws(()=>a.agentTaskAction('dot',input),/assigned agent/);
 assert.throws(()=>a.agentTaskAction('muse',{...input,version:99}),/changed/);
 const r=a.agentTaskAction('muse',input);assert.equal(r.task.status,'review');assert.equal(r.task.result.formState,'partially_filled');
 assert.deepEqual(a.agentTaskAction('muse',input),r);
 assert.equal(s.taskDb().prepare('SELECT body FROM task_requests WHERE id=?').get(`preparation-history:${t.id}:1`)!==undefined,true);
 assert.throws(()=>a.userTaskAction({action:'approve_application',taskId:t.id,version:r.task.version,answers:'Reviewed'}),/actual application form must be filled/);
 s.saveTask(s.newTask('application_submit','muse','Approved submit',{}, {entityId:t.entityId}));
 assert.throws(()=>a.agentTaskAction('muse',{...input,eventId:id(),version:r.task.version,formState:'filled'}),/already approved/);
});
test.after(()=>rmSync(dir,{recursive:true,force:true}));
